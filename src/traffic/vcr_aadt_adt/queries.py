"""
SQL query builders.

Every function in this module returns a SQL **string** that is byte-for-byte
identical (modulo whitespace) to the query generated by the legacy
``SMD_Package`` classes.  This is the primary defence against numerical drift.
"""

import numpy as np
import pandas as pd
from .smd_config import SMDConfigs
from . import config


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _get_veh_columns(connection, rtc_table, prefix='NUM_VEH'):
    """
    Discover vehicle columns from the RTC table header.
    Mirrors ``TrafficSummary.veh_columns``.
    """
    df = pd.read_sql(f"select * from {rtc_table} where rownum=1", con=connection)
    cols = np.array(df.columns.tolist())
    mask = np.char.startswith(cols, prefix)
    vehs = cols[mask]
    vehs.sort()
    return vehs.tolist()


# ---------------------------------------------------------------------------
# AADT queries  (TrafficSummary.post_class_aadt_sql)
# ---------------------------------------------------------------------------
def post_class_aadt_sql(routes, year, connection,
                        routeid_col='LINKID',
                        date_col='SURVEY_DATE',
                        hour_col='SURVEY_HOURS',
                        minute_col='SURVEY_MINUTE',
                        class_col='TRAFPOST',
                        temp_route_table='TEMP_REKAP_ROUTE_SELECTION',
                        postdesc_table='POSTDESC',
                        postdesc_prov='NOPROP',
                        postdesc_route='RUAS',
                        postdesc_sffx='SFFX',
                        postclass_table='POST_CLASS',
                        rtc_table=None):
    """
    Build the SQL that computes post-class AADT.
    """
    if rtc_table is None:
        rtc_table = config.RTC_TABLE_FMT.format(year=year)

    # Discover vehicle columns dynamically (same as legacy code)
    veh_columns = _get_veh_columns(connection, rtc_table, prefix=config.VEHICLE_COL_PREFIX)

    # ---- Level 1: RTC grouped by survey window --------------------------------
    rtc_select = (
        f"SELECT {routeid_col}, {date_col}, {hour_col}, {minute_col}, "
        f"substr(stats_mode(b.{class_col}), 1, 1) as {class_col}"
    )

    for num_veh_col in veh_columns:
        rtc_select += f"\n,SUM({num_veh_col}) as {num_veh_col}"

    if str(routes) != 'ALL':
        rtc_from = (
            f"\nFROM {rtc_table} a \n"
            f"LEFT JOIN {postdesc_table} b \n"
            f"ON a.{routeid_col} = CONCAT(CONCAT(b.{postdesc_prov}, b.{postdesc_route}), REPLACE(b.{postdesc_sffx}, ' ', ''))\n"
            f"WHERE {routeid_col} IN (SELECT {routeid_col} FROM {temp_route_table})\n"
            f"GROUP BY {routeid_col}, {date_col}, {hour_col}, {minute_col}"
        )
    else:
        rtc_from = (
            f"\nFROM {rtc_table} a \n"
            f"LEFT JOIN {postdesc_table} b \n"
            f"ON a.{routeid_col} = CONCAT(CONCAT(b.{postdesc_prov}, b.{postdesc_route}), REPLACE(b.{postdesc_sffx}, ' ', ''))\n"
            f"GROUP BY {routeid_col}, {date_col}, {hour_col}, {minute_col}"
        )

    rtc_select = rtc_select + rtc_from

    # ---- Level 2: Window sums & COUNT_HOUR ------------------------------------
    count_hour = (
        f"\n, CASE WHEN {class_col}='C' then"
        f"\nCOUNT({routeid_col}) OVER (PARTITION BY {routeid_col} ORDER BY {date_col}, {hour_col}, {minute_col} ROWS BETWEEN CURRENT ROW AND 63 FOLLOWING)*15/60.0 "
        f"ELSE COUNT({routeid_col}) OVER (PARTITION BY {routeid_col} ORDER BY {date_col}, {hour_col}, {minute_col} ROWS BETWEEN CURRENT ROW AND 159 FOLLOWING)*15/60.0 END AS COUNT_HOUR"
    )

    window_select = (
        f"SELECT {routeid_col}, {class_col}, TO_CHAR({date_col}, 'DAY') as SURVEY_DAY, "
        f"{hour_col}, {minute_col}"
    )

    for num_veh_col in veh_columns:
        window_select += (
            f"\n, CASE WHEN {class_col}='C' then "
            f"\nSUM({num_veh_col}) OVER (PARTITION BY {routeid_col} ORDER BY {date_col}, {hour_col}, {minute_col} ROWS BETWEEN CURRENT ROW AND 63 FOLLOWING)"
            f"\nELSE SUM({num_veh_col}) OVER (PARTITION BY {routeid_col} ORDER BY {date_col}, {hour_col}, {minute_col} ROWS BETWEEN CURRENT ROW AND 159 FOLLOWING) END AS {num_veh_col}"
        )

    window_select = window_select + count_hour + "\nFROM (\n" + rtc_select + "\n)"

    # ---- Level 3: Average multiplied by day factor ----------------------------
    final_select = f"SELECT {routeid_col}"

    for num_veh_col in veh_columns:
        final_select += (
            f"\n, CAST((CASE WHEN STATS_MODE({class_col})='C' THEN AVG({num_veh_col})*MAX(CLASS_1)"
            f" ELSE AVG({num_veh_col})*MAX(CLASS_2) END) AS INT) AS {num_veh_col}"
        )

    final_select = (
        final_select + "\nFROM (\n" + window_select + "\n)"
        f"LEFT JOIN {postclass_table} ON REPLACE(SURVEY_DAY, ' ', '') = DAY_OF_WEEK\n"
        f"WHERE (({hour_col} = 6 and {minute_col} = 0) or ({hour_col} = 5 and {minute_col} = 60)) and (COUNT_HOUR = 40 OR COUNT_HOUR = 16)\n"
        f"GROUP BY {routeid_col}"
    )

    return final_select


