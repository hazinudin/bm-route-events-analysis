# RNI queries  (TrafficVolume.get_rni_data_sql)
# ---------------------------------------------------------------------------
def get_rni_data_sql(routes, rni_table, temp_route_table='TEMP_REKAP_ROUTE_SELECTION',
                     routeid_col='LINKID',
                     from_m_col='FROM_STA',
                     to_m_col='TO_STA',
                     lane_width='LANE_WIDTH',
                     left_terr='LEFT_TERRAIN',
                     right_terr='RIGHT_TERRAIN',
                     road_type_col='ROAD_TYPE'):
    """
    Build the SQL that returns one aggregated row per route from the RNI table.
    """

    if str(routes) == 'ALL':
        segment_groupby = (
            f"SELECT {routeid_col}, {from_m_col}, {to_m_col},"
            f"sum({lane_width}) as {lane_width}, "
            f"greatest(max(substr({left_terr},2,1)), max(substr({right_terr},2,1))) as TERR \n"
            f"FROM {rni_table}\n"
            f"GROUP BY {routeid_col}, {from_m_col}, {to_m_col}"
        )

        route_type_groupby = (
            f"SELECT {routeid_col}, \n "
            f"MAX({road_type_col}) KEEP (DENSE_RANK FIRST ORDER BY C_TYPE DESC, ROAD_TYPE DESC) AS {road_type_col} \n"
            f"FROM \n (SELECT {routeid_col}, COUNT({road_type_col}) AS C_TYPE, {road_type_col}\n"
            f"FROM {rni_table}\n "
            f"GROUP BY {routeid_col}, {road_type_col})\n "
            f"GROUP BY {routeid_col}"
        )
    else:
        segment_groupby = (
            f"SELECT {routeid_col}, {from_m_col}, {to_m_col},"
            f"sum({lane_width}) as {lane_width}, "
            f"greatest(nvl(max(substr({left_terr},2,1)), 0), nvl(max(substr({right_terr},2,1)), 0)) as TERR \n"
            f"FROM {rni_table}\n"
            f"WHERE {routeid_col} IN (SELECT {routeid_col} FROM {temp_route_table})\n"
            f"GROUP BY {routeid_col}, {from_m_col}, {to_m_col}"
        )

        route_type_groupby = (
            f"SELECT {routeid_col}, \n "
            f"MAX({road_type_col}) KEEP (DENSE_RANK FIRST ORDER BY C_TYPE DESC, ROAD_TYPE DESC) AS {road_type_col} \n"
            f"FROM \n (SELECT {routeid_col}, COUNT({road_type_col}) AS C_TYPE, {road_type_col}\n"
            f"FROM {rni_table}\n "
            f"WHERE {routeid_col} IN (SELECT {routeid_col} FROM {temp_route_table})\n "
            f"GROUP BY {routeid_col}, {road_type_col})\n "
            f"GROUP BY {routeid_col}"
        )

    route_terr_groupby = (
        f"SELECT {routeid_col}, TERR, COUNT(TERR) as C_TERR, "
        f"AVG({lane_width}) as {lane_width} \nFROM (\n"
    )
    route_terr_groupby = route_terr_groupby + segment_groupby + "\n) GROUP BY LINKID, TERR"

    route_terr_lane_w = (
        f"SELECT {routeid_col}, "
        f"\nMAX(TERR) KEEP (DENSE_RANK FIRST ORDER BY C_TERR DESC, TERR ASC) AS TERR,"
        f"\nAVG({lane_width}) as {lane_width} "
        f"FROM(\n"
    )
    route_terr_lane_w = route_terr_lane_w + route_terr_groupby + "\n) GROUP BY LINKID"

    final_select = (
        f"SELECT a.*, b.{road_type_col} \nFROM (" + route_terr_lane_w + ") a \nLEFT JOIN (" +
        route_type_groupby + f") b \nON a.{routeid_col} = b.{routeid_col}"
    )

    return final_select


