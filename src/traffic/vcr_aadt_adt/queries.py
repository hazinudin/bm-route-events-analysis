# Capacity queries  (RoadCapacity.segment_capacity_sql & calculate_capacity)
# ---------------------------------------------------------------------------
def segment_capacity_sql(routes, year, aadt_df_sql, rni_table, temp_route_table,
                         capacity_coeff_table='CAPACITY_COEFF',
                         routeid_col='LINKID',
                         from_m_col='FROM_STA',
                         to_m_col='TO_STA',
                         segment_len_col='SEGMENT_LENGTH',
                         lane_width='LANE_WIDTH',
                         road_type_col='ROAD_TYPE',
                         left_terr='LEFT_TERRAIN',
                         right_terr='RIGHT_TERRAIN',
                         left_inner_sh_w='LEFT_INNER_SH_W',
                         left_outer_sh_w='LEFT_OUTER_SH_W',
                         right_inner_sh_w='RIGHT_INNER_SH_W',
                         right_outer_sh_w='RIGHT_OUTER_SH_W',
                         veh8_col='NUM_VEH8'):
    """
    Build the SQL that calculates capacity for every RNI segment.
    """

    # -- RNI subquery (aggregated per route/from_m) ----------------------------
    from .rni_summary import road_type_group_df as _rtg_df
    road_type_group_df = _rtg_df()
    road_type_group_series = road_type_group_df.groupby('ROAD_TYPE_GROUP')['ROAD_TYPE'].apply(lambda x: list(x))

    road_type_case = None
    for road_type_group, group_list in road_type_group_series.items():
        list_str = str(group_list).replace('[', '(').replace(']', ')')
        case = f" WHEN MAX({road_type_col}) IN {list_str} THEN {road_type_group}"
        if road_type_case is None:
            road_type_case = "CASE" + case
        else:
            road_type_case += case
    road_type_case += f" ELSE 0 END AS {road_type_col}"

    if str(routes) != 'ALL':
        rni_select = (
            f"SELECT {routeid_col}, {from_m_col}, \n"
            f"MAX({to_m_col}) as {to_m_col},"
            f"MAX({segment_len_col}) as {segment_len_col},"
            f"max(nvl(SUBSTR({left_terr}, 2, 1), 0)) as MAX_TERR_L, \n"
            f"max(nvl(SUBSTR({right_terr}, 2, 1), 0)) as MAX_TERR_R, \n"
            f"SUM({lane_width}) as {lane_width}, \n"
            f"SUM(nvl({left_inner_sh_w}, 0)) + SUM(nvl({left_outer_sh_w}, 0)) + SUM(nvl({right_inner_sh_w}, 0)) + "
            f"SUM(nvl({right_outer_sh_w}, 0)) as SHWIDTH, \n" + road_type_case +
            f"\nFROM {rni_table} \n"
            f"WHERE {routeid_col} IN (SELECT {routeid_col} FROM {temp_route_table}) \n"
            f"GROUP BY {routeid_col}, {from_m_col}"
        )
    else:
        rni_select = (
            f"SELECT {routeid_col}, {from_m_col}, \n"
            f"MAX({to_m_col}) as {to_m_col},"
            f"MAX({segment_len_col}) as {segment_len_col},"
            f"SUBSTR(MAX({left_terr}), 2, 1) as MAX_TERR_L, \n"
            f"SUBSTR(MAX({right_terr}), 2, 1) as MAX_TERR_R, \n"
            f"SUM({lane_width}) as {lane_width}, \n"
            f"SUM({left_inner_sh_w}) + SUM({left_outer_sh_w}) + SUM({right_inner_sh_w}) + "
            f"SUM({right_outer_sh_w}) as SHWIDTH, \n" + road_type_case +
            f"\nFROM {rni_table} \n"
            f"GROUP BY {routeid_col}, {from_m_col}"
        )

    # -- AADT subquery ---------------------------------------------------------
    aadt_select = aadt_df_sql

    # -- Join RNI + AADT -------------------------------------------------------
    rni_aadt_join = (
        f"SELECT t1.*, t2.{veh8_col}, "
        f"GREATEST(t1.MAX_TERR_L, t1.MAX_TERR_R) as MAX_TERR \n"
        f"FROM (\n{aadt_select}\n) t2\n"
        f"LEFT JOIN \n(\n{rni_select}\n) t1\n"
        f"ON t1.{routeid_col} = t2.{routeid_col}"
    )

    # -- Capacity formula (FCSF, FCSP, FCW) ------------------------------------
    fcsf = (
        "("
        "coeff.F1 - "
        "LEAST("
        "("
        f"coeff.F2*POWER(GREATEST((LEAST(joined.{veh8_col}, 2300)-200), 0), coeff.F3) +\n"
        f"POWER(coeff.F4*GREATEST((joined.SHWIDTH-0.5), 0), coeff.F5) *\n"
        f"GREATEST((LEAST(joined.{veh8_col}, 2300)-coeff.F6), 0)"
        ")"
        ", 0)"
        ")"
    )

    fcsp = "(0.97)"

    fcw = f"(coeff.W1 + coeff.W2*(joined.{lane_width}) + coeff.W3*POWER(joined.{lane_width}, 2))"

    cap = "(" + "coeff.BASE*" + fcw + "*" + fcsp + "*" + fcsf + ") as CAP"

    coeff_join = (
        f"SELECT joined.{routeid_col}, joined.{from_m_col}, joined.{to_m_col}, "
        f"joined.{segment_len_col}, " + cap +
        f"\nFROM\n({rni_aadt_join}\n) joined\n"
        f"LEFT JOIN\n({capacity_coeff_table}\n) coeff\n"
        f"on joined.{road_type_col} = coeff.ROAD_TYPE\n"
        f"AND joined.MAX_TERR = coeff.TERRAIN"
    )

    return coeff_join


def calculate_capacity_sql(segment_capacity_sql, routeid_col='LINKID',
                           segment_len_col='SEGMENT_LENGTH', year=2021):
    """
    Wrap ``segment_capacity_sql`` in the weighted-average GROUP BY.
    """
    return (
        f"SELECT {routeid_col}, SUM(CAP*{segment_len_col})/SUM({segment_len_col}) WEIGHTED_CAP,"
        f"{year} AS YEAR\n "
        f"FROM\n({segment_capacity_sql}\n)\n GROUP BY {routeid_col}"
    )
